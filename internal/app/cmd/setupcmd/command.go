// Package setupcmd provides `dh-waypoint init` and `dh-waypoint doctor`:
// first-run scaffolding (config file, environment file with generated
// secrets, plugins directory) and a read-only installation check.
// Neither command needs a database; doctor only probes TCP
// reachability and reports it as such.
package setupcmd

import (
	"crypto/rand"
	"encoding/hex"
	"fmt"
	"net"
	"os"
	"path/filepath"
	"time"

	"github.com/spencernorton/DH-Waypoint/internal/database/postgres"
	"github.com/spencernorton/DH-Waypoint/internal/processor"
	"github.com/spencernorton/DH-Waypoint/internal/processors"
	"github.com/urfave/cli/v2"
	"go.uber.org/fx"
)

type Params struct {
	fx.In
	Processing processor.Config
	Processors processors.Config
	Postgres   postgres.Config
}

type Result struct {
	fx.Out
	InitCommand   *cli.Command `group:"commands"`
	DoctorCommand *cli.Command `group:"commands"`
}

const configTemplate = `# DH-Waypoint configuration. Every value here can also be set (and is
# overridden) by an environment variable; run ` + "`dh-waypoint config show`" + `
# to see every resolved value and where it came from. Full reference:
# docs/configuration.md

# Processing mode: full | basic | raw
#   full  - built-in CEL classifier, title parsing and matching (default)
#   basic - core stamps only a coarse category from file extensions;
#           use with a processor plugin doing real classification
#   raw   - core stores metainfo untouched; plugins do everything
processing:
  mode: basic

processors:
  # Drop *.plugin.yml files in this directory to register plugins.
  plugins_dir: plugins
`

const samplePlugin = `# Sample plugin file. Rename to enable:
#   mv sample-filter.plugin.yml.disabled sample-filter.plugin.yml
# The running core picks it up within 30 seconds; no restart needed.
# mode: shadow records what the filter would do without changing the
# catalogue. Switch to apply when the shadow results look right.
driver: builtin/filter-list
mode: shadow
configuration:
  block_patterns:
    - "(?i)\\bsample\\b.*\\bonly\\b"
  reason: "sample-only releases"
`

func secret() (string, error) {
	buf := make([]byte, 32)
	if _, err := rand.Read(buf); err != nil {
		return "", err
	}
	return hex.EncodeToString(buf), nil
}

func writeNewFile(path string, content string, perm os.FileMode, force bool, written *[]string, skipped *[]string) error {
	if !force {
		if _, err := os.Stat(path); err == nil {
			*skipped = append(*skipped, path)
			return nil
		}
	}
	if err := os.WriteFile(path, []byte(content), perm); err != nil {
		return err
	}
	*written = append(*written, path)
	return nil
}

func New(p Params) (Result, error) {
	initCmd := &cli.Command{
		Name:  "init",
		Usage: "Scaffold config.yml, .env with generated secrets, and a plugins directory",
		Flags: []cli.Flag{
			&cli.StringFlag{Name: "dir", Value: ".", Usage: "directory to scaffold"},
			&cli.BoolFlag{Name: "force", Usage: "overwrite existing files"},
		},
		Action: func(ctx *cli.Context) error {
			dir := ctx.String("dir")
			force := ctx.Bool("force")
			if err := os.MkdirAll(filepath.Join(dir, "plugins"), 0o755); err != nil {
				return err
			}
			pgPass, err := secret()
			if err != nil {
				return err
			}
			torznabKey, err := secret()
			if err != nil {
				return err
			}
			adminToken, err := secret()
			if err != nil {
				return err
			}
			envContent := "# Generated by `dh-waypoint init`. Keep this file private (chmod 600).\n" +
				"POSTGRES_PASSWORD=" + pgPass + "\n" +
				"TORZNAB_API_KEY=" + torznabKey + "\n" +
				"PROCESSORS_ADMIN_TOKEN=" + adminToken + "\n"
			var written, skipped []string
			if err := writeNewFile(filepath.Join(dir, "config.yml"), configTemplate, 0o644, force, &written, &skipped); err != nil {
				return err
			}
			if err := writeNewFile(filepath.Join(dir, ".env"), envContent, 0o600, force, &written, &skipped); err != nil {
				return err
			}
			if err := writeNewFile(filepath.Join(dir, "plugins", "sample-filter.plugin.yml.disabled"), samplePlugin, 0o644, force, &written, &skipped); err != nil {
				return err
			}
			for _, f := range written {
				fmt.Fprintf(ctx.App.Writer, "wrote %s\n", f)
			}
			for _, f := range skipped {
				fmt.Fprintf(ctx.App.Writer, "kept existing %s (use --force to overwrite)\n", f)
			}
			fmt.Fprintln(ctx.App.Writer, "Next: docker compose up -d, then `dh-waypoint doctor`.")
			return nil
		},
	}

	doctorCmd := &cli.Command{
		Name:  "doctor",
		Usage: "Check configuration, database reachability, and plugin files",
		Action: func(ctx *cli.Context) error {
			out := ctx.App.Writer
			failed := 0
			report := func(ok bool, label, detail string) {
				mark := "ok  "
				if !ok {
					mark = "FAIL"
					failed++
				}
				fmt.Fprintf(out, "[%s] %s: %s\n", mark, label, detail)
			}

			mode := p.Processing.Mode.Normalize()
			report(mode.Valid(), "processing.mode", string(mode))

			if p.Postgres.DSN != "" {
				report(true, "postgres", "DSN configured (not probed)")
			} else {
				addr := net.JoinHostPort(p.Postgres.Host, fmt.Sprint(p.Postgres.Port))
				conn, err := net.DialTimeout("tcp", addr, 3*time.Second)
				if err != nil {
					report(false, "postgres tcp "+addr, err.Error())
				} else {
					_ = conn.Close()
					report(true, "postgres tcp "+addr, "reachable (TCP only, credentials not checked)")
				}
			}

			dir := p.Processors.PluginsDir
			if dir == "" {
				report(true, "plugins directory", "disabled")
			} else {
				specs, err := processors.LoadPluginDir(dir)
				if err != nil {
					report(false, "plugins directory "+dir, err.Error())
				} else {
					report(true, "plugins directory "+dir, fmt.Sprintf("%d valid plugin file(s)", len(specs)))
				}
				for _, s := range specs {
					fmt.Fprintf(out, "        %s (%s)\n", s.ID, s.Path)
				}
			}

			if failed > 0 {
				return cli.Exit(fmt.Sprintf("doctor found %d problem(s)", failed), 1)
			}
			return nil
		},
	}

	return Result{InitCommand: initCmd, DoctorCommand: doctorCmd}, nil
}
